"""Measures each request: time to first token, total time, and tokens per second.

Three views of the same numbers:
- /metrics            -> summary since startup (percentiles), for humans and the demo page
- /metrics/timeseries -> one bucket per second for the last 5 minutes, for the live charts
- /metrics/prometheus -> standard format read by monitoring tools (Prometheus + Grafana)
"""
import logging
import time
from collections import deque

from prometheus_client import Counter, Gauge, Histogram

log = logging.getLogger("llm.metrics")

# Prometheus metrics. A histogram counts requests into time ranges ("buckets"), so a monitoring
# tool can compute percentiles like p95 over any time window.
PROM_REQUESTS = Counter("llm_requests_total", "Finished requests by status", ["status"])
PROM_TOKENS = Counter("llm_completion_tokens_total", "Tokens generated by the model")
PROM_TTFT = Histogram("llm_ttft_seconds", "Time to first token",
                      buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 30))
PROM_LATENCY = Histogram("llm_request_latency_seconds", "Total request time",
                         buckets=(0.25, 0.5, 1, 2, 5, 10, 30, 60, 120))
PROM_IN_FLIGHT = Gauge("llm_in_flight", "Requests being answered right now")
PROM_WAITING = Gauge("llm_waiting", "Requests waiting for a free slot")
PROM_CACHE_ENTRIES = Gauge("llm_cache_entries", "Answers stored in the response cache")


class RequestTimer:
    """Timeline of one request: arrived (t0) -> got a slot -> first token -> finished."""

    def __init__(self, model: str | None = None):
        self.model = model
        self.t0 = time.perf_counter()
        self.t_slot: float | None = None
        self.t_first: float | None = None

    def got_slot(self) -> None:
        self.t_slot = time.perf_counter()

    def first_token(self) -> None:
        if self.t_first is None:
            self.t_first = time.perf_counter()

    def finish(self, completion_tokens: int, status: str = "ok") -> dict:
        t_end = time.perf_counter()
        t_first = self.t_first or t_end  # non-streaming: the first word arrives with the last one
        if self.t_first and t_end > self.t_first and completion_tokens > 1:
            # Streaming: writing speed after the first token (excludes waiting + prompt reading).
            tps = (completion_tokens - 1) / (t_end - self.t_first)
        else:
            # Non-streaming: we only know the total time.
            tps = completion_tokens / max(t_end - self.t0, 1e-6)
        m = {
            "time": round(time.time(), 1),
            "model": self.model,
            "status": status,
            "queue_ms": round(((self.t_slot or self.t0) - self.t0) * 1000, 1),  # waiting in line
            "ttft_ms": round((t_first - self.t0) * 1000, 1),
            "latency_ms": round((t_end - self.t0) * 1000, 1),
            "completion_tokens": completion_tokens,
            "tokens_per_sec": round(tps, 1),
        }
        log.info("request_done %s", m)
        STATS.record(m)
        return m


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    return s[min(len(s) - 1, int(round(p / 100 * (len(s) - 1))))]


class Stats:
    """Running totals since the server started (kept in memory, last 1000 requests)."""

    def __init__(self, keep: int = 1000, history_seconds: int = 300):
        self.keep = keep
        self.records: list[dict] = []
        self.status_counts: dict[str, int] = {}
        self.started = time.time()
        self.seconds: deque[dict] = deque(maxlen=history_seconds)  # oldest second drops off
        self.recent: deque[dict] = deque(maxlen=25)  # last requests of any status, newest first

    def _bucket(self) -> dict:
        """The bucket for the current second (created if this second has none yet)."""
        now = int(time.time())
        if not self.seconds or self.seconds[-1]["t"] != now:
            self.seconds.append({"t": now, "requests": 0, "tokens": 0, "errors": 0, "ttft_ms": [],
                                 "in_flight": 0, "waiting": 0})
        return self.seconds[-1]

    def record(self, m: dict) -> None:
        self.status_counts[m["status"]] = self.status_counts.get(m["status"], 0) + 1
        PROM_REQUESTS.labels(m["status"]).inc()
        self.recent.appendleft(m)
        b = self._bucket()
        b["requests"] += 1
        if m["status"] in ("error", "timeout", "rejected"):
            b["errors"] += 1
        if m["status"] == "ok":
            self.records = (self.records + [m])[-self.keep:]
            b["tokens"] += m["completion_tokens"]
            b["ttft_ms"].append(m["ttft_ms"])
            PROM_TOKENS.inc(m["completion_tokens"])
            PROM_TTFT.observe(m["ttft_ms"] / 1000)
            PROM_LATENCY.observe(m["latency_ms"] / 1000)

    def sample_queue(self, in_flight: int, waiting: int, cache_entries: int) -> None:
        """Called once per second, so every second has a bucket even when nothing finishes."""
        b = self._bucket()
        b["in_flight"], b["waiting"] = in_flight, waiting
        PROM_IN_FLIGHT.set(in_flight)
        PROM_WAITING.set(waiting)
        PROM_CACHE_ENTRIES.set(cache_entries)

    def by_model(self) -> list[dict]:
        """Per-model comparison from the successful requests kept in memory."""
        groups: dict[str, list[dict]] = {}
        for r in self.records:
            groups.setdefault(r["model"], []).append(r)
        return [{"model": model, "requests": len(rs),
                 "ttft_ms_p50": percentile([r["ttft_ms"] for r in rs], 50),
                 "tokens_per_sec_avg": round(sum(r["tokens_per_sec"] for r in rs) / len(rs), 1)}
                for model, rs in sorted(groups.items(), key=lambda kv: -len(kv[1]))]

    def timeseries(self) -> dict:
        return {"uptime_s": round(time.time() - self.started), "points": list(self.seconds)}

    def summary(self) -> dict:
        ttft = [r["ttft_ms"] for r in self.records]
        lat = [r["latency_ms"] for r in self.records]
        tps = [r["tokens_per_sec"] for r in self.records]
        return {
            "requests_by_status": self.status_counts,
            "ttft_ms": {"p50": percentile(ttft, 50), "p95": percentile(ttft, 95)},
            "latency_ms": {"p50": percentile(lat, 50), "p95": percentile(lat, 95)},
            "tokens_per_sec_avg": round(sum(tps) / len(tps), 1) if tps else 0.0,
        }


STATS = Stats()
